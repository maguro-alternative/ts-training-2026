// 課題 06: 型パズル
//
// 標準の Partial, Pick, Readonly などを使わずに、同じ機能の型を自作する。

// ------------------------------------------------------------
// 1. MyPartial<T>: 全プロパティをオプショナルにする
// ------------------------------------------------------------
// 標準の Partial<T> と同等のものを自作する。
// TODO: Mapped Types と `?` を使う
export type MyPartial<T> = any;

// ------------------------------------------------------------
// 2. MyReadonly<T>: 全プロパティを readonly にする
// ------------------------------------------------------------
// 標準の Readonly<T> と同等。
// TODO: Mapped Types と `readonly` を使う
export type MyReadonly<T> = any;

// ------------------------------------------------------------
// 3. MyPick<T, K extends keyof T>: 指定したキーだけ取り出す
// ------------------------------------------------------------
// 標準の Pick<T, K> と同等。
export type MyPick<T, K extends keyof T> = any;

// ------------------------------------------------------------
// 4. MyExclude<T, U>: T から U に代入できる型を除く
// ------------------------------------------------------------
// 例: MyExclude<"a" | "b" | "c", "a"> -> "b" | "c"
// TODO: Conditional Types を使う
export type MyExclude<T, U> = any;

// ------------------------------------------------------------
// 5. NonNullable<T>: null と undefined を除外
// ------------------------------------------------------------
// 例: MyNonNullable<string | null | undefined> -> string
export type MyNonNullable<T> = any;

// ------------------------------------------------------------
// 6. First<T>: タプルの先頭要素の型を取り出す
// ------------------------------------------------------------
// 例: First<[1, 2, 3]> -> 1
// 空配列のときは never
// TODO: Conditional Types + タプル分解パターン
export type First<T extends readonly unknown[]> = any;

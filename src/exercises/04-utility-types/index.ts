// 課題 04: ユーティリティ型

export type User = {
  id: string;
  name: string;
  email: string;
  age: number;
};

// ------------------------------------------------------------
// 1. UserUpdate: User の全プロパティをオプショナルにした型
// ------------------------------------------------------------
// 「更新リクエスト」では一部のプロパティだけ変更したいので、全プロパティ任意。
// TODO: Partial を使う
export type UserUpdate = any;

// ------------------------------------------------------------
// 2. UserPublic: User から email と age を除いた型
// ------------------------------------------------------------
// 「公開プロフィール」では個人情報は出さない。
// TODO: Omit を使う
export type UserPublic = any;

// ------------------------------------------------------------
// 3. UserSummary: User の id と name だけを持つ型
// ------------------------------------------------------------
// TODO: Pick を使う
export type UserSummary = any;

// ------------------------------------------------------------
// 4. UserDictionary: ユーザーIDをキーに User を引けるマップ型
// ------------------------------------------------------------
// 例: { "u1": User, "u2": User, ... }
// TODO: Record を使う
export type UserDictionary = any;

// ------------------------------------------------------------
// 5. 関数: createUser
// ------------------------------------------------------------
// User を作る関数。id はサーバー側で振るので引数には含めない。
// TODO: 引数の型は Omit<User, 'id'> を使う
export function createUser(input: any): User {
  return { id: 'generated-id', ...input };
}

// ------------------------------------------------------------
// 6. 関数: updateUser
// ------------------------------------------------------------
// ユーザーの一部のプロパティを更新する関数。id は必須、他は任意。
// TODO: patch の型は Partial<Omit<User, 'id'>> を使う
export function updateUser(user: User, patch: any): User {
  return { ...user, ...patch };
}
